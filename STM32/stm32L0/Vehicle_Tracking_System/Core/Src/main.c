/**
 * @brief  Ask the ESP32 for the latest GPS string via I2C.
 * @param  buf     Buffer to receive the null-terminated location string.
 * @param  buflen  Size of buf.
 * @return 1 if a valid-looking location was received, 0 on error.
 */
static uint8_t GPS_Read_From_ESP32(char *buf, uint16_t buflen)
{
    uint8_t tmp[GPS_STR_LEN];
    memset(tmp, 0, sizeof(tmp));

    HAL_StatusTypeDef st = HAL_I2C_Master_Receive(
            &hi2c1, ESP32_I2C_ADDR, tmp, GPS_STR_LEN - 1, HAL_MAX_DELAY);

    if (st != HAL_OK)
        return 0;

    tmp[GPS_STR_LEN - 1] = '\0';

    /* Minimal validity check: must contain a comma (lat,lon format) */
//    if (strchr((char *)tmp, ',') == NULL)
//        return 0;

    strncpy(buf, (char *)tmp, buflen - 1);
    buf[buflen - 1] = '\0';
    return 1;
}

/**
 * @brief  Flush all buffered GPS locations to SMS, then clear the buffer.
 */
static void Flush_Stored_Locations(void)
{
    char locs[GPS_MAX_ENTRIES][GPS_SLOT_SIZE];
    uint8_t n = GPS_Storage_ReadAll(locs);

    if (n == 0)
        return;

    char sms[160];
    /* Send one SMS per stored location to keep each message short */
    for (uint8_t i = 0; i < n; i++)
    {
        snprintf(sms, sizeof(sms), "GPS(stored %u/%u): %s", i + 1, n, locs[i]);
        SIM800_SendSMS(PHONE_NUMBER, sms);
        //EPD_Print(sms);
        HAL_Delay(3000);   /* give GSM module breathing room between SMSes  */
    }

    GPS_Storage_Clear();
    EPD_Print("Buffer flushed");
}

/* ── Application entry point ─────────────────────────────────────────────── */

int main(void)
{
    /* --- MCU init -------------------------------------------------------- */
    HAL_Init();
    SystemClock_Config();

    MX_GPIO_Init();
    MX_I2C1_Init();
    MX_SPI1_Init();
    MX_SPI2_Init();
    MX_TIM2_Init();
    MX_USART1_UART_Init();
    EPD_Init();
    EPD_Print("EPD : OK");
    /* --- Subsystem init -------------------------------------------------- */
    GPS_Storage_Init();           /* restore circular buffer state from flash */
    EPD_Print("FLASH : OK");
    /* Start 1-second TIM2 tick */
    HAL_TIM_Base_Start_IT(&htim2);
    EPD_Print("TIMER : OK");
    HAL_Delay(1000);
    /* --- Main loop ------------------------------------------------------- */

    while (1)
    {
        if (!send_sms_flag)
        {
            HAL_PWR_EnterSLEEPMode(PWR_MAINREGULATOR_ON, PWR_SLEEPENTRY_WFI);
            continue;
        }

        /* ── 30-second tick ───────────────────────────────────────────── */
        send_sms_flag = 0;

        /* 1. Read GPS from ESP32 */
        char location[GPS_SLOT_SIZE];
        uint8_t gps_ok = GPS_Read_From_ESP32(location, sizeof(location));

        if (!gps_ok)
        {
            EPD_Print("No GPS fix");
            /* Nothing to store or send — skip this cycle */
            continue;
        }

        EPD_Print(location);

        /* 2. Check GSM signal */
        Check_Network_Status();

        if (network_ok)
        {
            /* 2a. Signal present — flush buffer first (if any), then send live */
            if (GPS_Storage_Count() > 0)
            {
                EPD_Print("Flushing buffer...");
                Flush_Stored_Locations();
            }

            char sms[160];
            snprintf(sms, sizeof(sms), "GPS: %s", location);
            SIM800_SendSMS(PHONE_NUMBER, sms);
        }
        else
        {
            /* 2b. No signal — store in flash circular buffer */
            GPS_Storage_Save(location);

            char disp[48];
            snprintf(disp, sizeof(disp), "Stored %u/5", GPS_Storage_Count());
            EPD_Print(disp);
        }
    }
}

/* ── TIM2 ISR — fires every 1 second ────────────────────────────────────── */

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2)
    {
        seconds++;
        if (seconds >= 30)
        {
            send_sms_flag = 1;
            seconds       = 0;
        }
    }
}

