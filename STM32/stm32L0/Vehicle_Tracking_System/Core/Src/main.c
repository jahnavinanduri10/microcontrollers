/*
 * main.c  –  Vehicle GPS Tracker  (STM32L0538-DISCO)
 *
 * Hardware connections
 * ───────────────────
 *  I2C1  PB6/PB7  → ESP32 (GPS over I2C slave, addr 0x08)
 *  UART1 PA9/PA10 → SIM800L GSM module
 *  SPI2  PB13-15  → W25Qxx external flash  (CS = PB0)
 *  SPI1            → E-Paper display  (already working)
 *
 * Behaviour
 * ─────────
 *  Every 30 s (TIM2 interrupt):
 *    1. Read GPS string from ESP32 over I2C.
 *    2. If GSM signal available  → send SMS immediately.
 *       Else                     → store in flash circular buffer (max 5).
 *    3. Whenever signal returns  → flush all buffered locations via SMS,
 *                                   then clear the buffer.
 */

/*PB6     ------> I2C1_SCL
  PB7     ------> I2C1_SDA*/
/* PA9  ------> USART1_TX
   PA10 ------> USART1_RX*/
/**SPI2 GPIO Configuration
  PB13     ------> SPI2_SCK
  PB14     ------> SPI2_MISO
  PB15     ------> SPI2_MOSI  */

