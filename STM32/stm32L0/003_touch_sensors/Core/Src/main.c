static void MX_TSC_Init(void);

int main(void)
{
  HAL_Init();

  SystemClock_Config();

  MX_GPIO_Init();
  MX_TSC_Init();
  volatile uint32_t value;

    while (1)
    {
        HAL_TSC_Start(&htsc);

        HAL_TSC_PollForAcquisition(&htsc);

        value = HAL_TSC_GroupGetValue(&htsc,
                                      TSC_GROUP1_IDX);

        HAL_TSC_Stop(&htsc);

        if(value < 1320)
        {
            HAL_GPIO_WritePin(GPIOA,
                              GPIO_PIN_5,
                              GPIO_PIN_SET);
        }
        else
        {
            HAL_GPIO_WritePin(GPIOA,
                              GPIO_PIN_5,
                              GPIO_PIN_RESET);
        }

        HAL_Delay(50);
    }
}

